import { NextRequest, NextResponse } from "next/server";
import { cloudStore } from "@/lib/data-store";
import JSZip from "jszip";

export async function GET(
  req: NextRequest,
  { params }: { params: { projectId: string } | Promise<{ projectId: string }> }
) {
  const { projectId } = await Promise.resolve(params);
  const project = cloudStore.projects.find((p) => p.id === projectId);

  if (!project) {
    return NextResponse.json({ detail: "Project not found" }, { status: 404 });
  }

  const deliverables = cloudStore.deliverables.filter((d) => d.project_id === projectId);

  const zip = new JSZip();
  const rootFolder = zip.folder(project.slug || "project");

  // Add project manifest
  rootFolder?.file(
    "project.json",
    JSON.stringify(
      {
        name: project.name,
        slug: project.slug,
        description: project.description,
        exported_at: new Date().toISOString(),
        agency: "IBS AI Workforce",
      },
      null,
      2
    )
  );

  // Add all files
  if (deliverables.length > 0) {
    for (const d of deliverables) {
      rootFolder?.file(d.file_name, d.raw_content || `# ${d.file_name}\n\nDeliverable generated by ${d.created_by_agent_id}`);
    }
  } else {
    rootFolder?.file("README.md", `# ${project.name}\n\nProject initialized under IBS AI Workforce.`);
  }

  const content = await zip.generateAsync({ type: "uint8array" });

  return new Response(content as any, {
    headers: {
      "Content-Type": "application/zip",
      "Content-Disposition": `attachment; filename="${project.slug}-workspace.zip"`,
    },
  });
}
